def check_api_compatibility(api_version_attr: object) -> str | None:
    """Return an error message when a plugin targets a different API version.

    Args:
        api_version_attr: The plugin module's ``__bekas_api_version__`` value.

    Returns:
        None when compatible, otherwise a human-readable error message.
    """
    if api_version_attr is None:
        return None  # third-party plugins predating the SDK contract keep loading
    try:
        version = int(str(api_version_attr))
    except (TypeError, ValueError):
        return f"invalid __bekas_api_version__ value: {api_version_attr!r}"
    if version != API_VERSION:
        return (
            f"plugin targets bekas plugin API v{version} but this bekas implements "
            f"v{API_VERSION}; upgrade or reinstall the plugin for a compatible version"
        )
    return None


def scaffold_plugin(name: str, target_dir: Path) -> Path:
    """Write a ready-to-edit plugin package skeleton.

    Args:
        name: Short plugin id (lowercase, dotted names are lower-cased).
        target_dir: Directory in which ``bekas-plugin-<name>/`` is created.

    Returns:
        The created package directory.

    Raises:
        ValueError: When ``name`` is not a valid python package slug.
    """
    slug = name.strip().lower().replace("-", "_").replace(".", "_")
    if not slug or not slug.replace("_", "").isalnum():
        raise ValueError(f"Invalid plugin name: {name!r} (use letters, digits, dots or dashes)")
    class_name = "".join(part.capitalize() for part in slug.split("_")) + "Plugin"
    pkg_dir = target_dir / f"bekas-plugin-{slug}"
    mod_dir = pkg_dir / f"bekas_plugin_{slug}"
    mod_dir.mkdir(parents=True, exist_ok=True)

    description = f"{slug} cleanup plugin for bekas"
    template = _PLUGIN_TEMPLATE.format(
        name=slug, description=description, class_name=class_name, api_version=API_VERSION
    )
    (mod_dir / "__init__.py").write_text(f'"""bekas plugin package: {slug}."""\n')
    (mod_dir / "plugin.py").write_text(template.replace("measure(target)", "_measure(target)"))
    (pkg_dir / "pyproject.toml").write_text(
        _SETUP_TEMPLATE.format(name=slug, description=description, class_name=class_name, api_version=API_VERSION)
    )
    (pkg_dir / "README.md").write_text(_PKG_TEMPLATE.format(name=slug, description=description))
    test_file = pkg_dir / "test_plugin.py"
    test_file.write_text(_TEST_TEMPLATE.format(slug=slug, class_name=class_name))
    return pkg_dir


